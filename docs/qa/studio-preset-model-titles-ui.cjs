// Model-aware native Studio poster text regression; no canvas controller replacement.
const {chromium}=require('playwright'),assert=require('node:assert/strict'),os=require('os'),path=require('path');
(async()=>{
  const vp=JSON.parse(process.env.VP||'{"width":390,"height":844}');
  const b=await chromium.launch({headless:true,...(process.env.QA_CHROMIUM_PATH?{executablePath:process.env.QA_CHROMIUM_PATH}:{}),args:['--no-sandbox','--use-gl=swiftshader','--enable-unsafe-swiftshader']});
  const p=await b.newPage({viewport:vp,isMobile:vp.width<700,hasTouch:vp.width<900,deviceScaleFactor:+process.env.QA_DPR||1});
  const errors=[];p.on('pageerror',e=>errors.push(e.message));
  await p.addInitScript(()=>localStorage.setItem('cerebra-hide-welcome','true'));
  await p.goto(process.env.QA_URL||'http://127.0.0.1:8000');
  await p.locator('#gateway').waitFor({state:'visible',timeout:180000});
  await p.locator('#gateway .gateway-enter').first().click();
  await p.locator('.cl-page.cl-hub-open').waitFor({state:'visible'});
  await p.locator('[data-cl-enter]').click();
  const skip=p.getByRole('button',{name:'Skip and enter Studio'});
  if(await skip.isVisible())await skip.click();
  await p.waitForFunction(()=>window.__cerebra?.studio?.active&&!!window.CerebraModelPresetTitles,{timeout:120000});
  const result=await p.evaluate(()=>{
    const s=__cerebra.studio;
    const rocket=model=>{
      const it=s.addItem('kit',{kit:'rocket',name:({f9:'Falcon 9',sv:'Saturn V'})[model],p:{...CerebraRockets.kit.defaults,model},opacity:1});
      s.select(it);return it;
    };
    rocket('f9');
    s.applyPreset('ember');
    const title=s.items.find(it=>it.role==='title');
    const kicker=s.items.find(it=>it.role==='kicker');
    if(!title||!kicker)throw Error('Native roles not generated by poster preset');
    const first={name:CerebraModelPresetTitles.current(),title:title.content,kicker:kicker.content};
    title.content='CUSTOM TITLE';title.edited=true;title.el.textContent=title.content;
    rocket('sv');
    const second={name:CerebraModelPresetTitles.current(),title:title.content,kicker:kicker.content};
    s.setSubject(0);
    const third={name:CerebraModelPresetTitles.current(),title:title.content,kicker:kicker.content,world:s.app.orrery.worlds[0].def.name};
    return {first,second,third,unmodified:title.edited};
  });
  console.log('MODEL_TITLE_SYNC',JSON.stringify(result));
  assert.equal(result.first.name,'Falcon 9');
  assert.equal(result.first.title,'Falcon 9');
  assert.match(result.first.kicker,/Falcon 9/i);
  assert.equal(result.second.name,'Saturn V');
  assert.equal(result.second.title,'CUSTOM TITLE');
  assert.match(result.second.kicker,/Saturn V/i);
  assert.equal(result.third.name,result.third.world);
  assert.equal(result.third.title,'CUSTOM TITLE');
  assert.match(result.third.kicker,new RegExp(result.third.world.replace(/[.*+?^${}()|[\]\\]/g,'\\$&'),'i'));
  assert.deepEqual(errors,[]);
  await p.screenshot({path:path.join(process.env.QA_SCREENSHOT_DIR||os.tmpdir(),`model-titles-${vp.width}x${vp.height}.png`)});
  console.log('PASS',JSON.stringify(vp));
  await b.close();
})().catch(e=>{console.error(e);process.exit(1)});
